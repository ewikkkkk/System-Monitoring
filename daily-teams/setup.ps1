#requires -Version 7.0
param([switch]$Run, [switch]$TestSend)
$ErrorActionPreference = 'Stop'
$deliveryFolder = Join-Path $PSScriptRoot '.local'
$exportFolder = Join-Path $PSScriptRoot 'exports'
$secretFile = Join-Path $deliveryFolder 'webhook.txt'
$node = (Get-Command node -CommandType Application).Source
$sender = Join-Path $PSScriptRoot 'send.mjs'
if (-not (Test-Path -LiteralPath (Join-Path $PSScriptRoot 'node_modules/xlsx/package.json'))) {
  throw 'Run npm ci from the daily-teams folder first.'
}

if ($Run -or $TestSend) {
  if (Test-Path -LiteralPath $secretFile) {
    $secret = Get-Content -LiteralPath $secretFile -Raw | ConvertTo-SecureString
  } elseif ($TestSend) {
    $secret = Read-Host 'Paste the Teams Workflows test webhook URL (hidden)' -AsSecureString
  } else {
    throw 'Run setup.ps1 first.'
  }
  $env:DAILY_TEAMS_WEBHOOK_URL = [Net.NetworkCredential]::new('', $secret).Password
  $env:DAILY_TEAMS_EXPORT_DIR = $exportFolder
  $env:DAILY_TEAMS_STATE_DIR = $deliveryFolder
  try {
    if ($TestSend) { & $node $sender --test }
    else { & $node $sender *>> (Join-Path $deliveryFolder 'delivery.log') }
    exit $LASTEXITCODE
  } finally {
    Remove-Item Env:DAILY_TEAMS_WEBHOOK_URL -ErrorAction SilentlyContinue
  }
}

$secret = Read-Host 'Paste the Teams Workflows webhook URL (hidden)' -AsSecureString
$raw = [Net.NetworkCredential]::new('', $secret).Password
$url = $null
if (-not [Uri]::TryCreate($raw, [UriKind]::Absolute, [ref]$url) -or
    $url.Scheme -ne 'https' -or $url.UserInfo -or $url.Fragment -or
    $url.Host -notmatch '(?:^|\.)(?:api\.powerplatform\.com|logic\.azure\.com)$') {
  throw 'Enter the HTTPS webhook URL generated by Teams Workflows.'
}
$raw = $null
$url = $null
New-Item -ItemType Directory -Force -Path $deliveryFolder | Out-Null
New-Item -ItemType Directory -Force -Path $exportFolder | Out-Null
# On Windows, the encrypted file can be opened only by this account on this PC.
$secret | ConvertFrom-SecureString | Set-Content -LiteralPath $secretFile
$action = New-ScheduledTaskAction -Execute (Get-Process -Id $PID).Path -Argument ('-NoProfile -NonInteractive -WindowStyle Hidden -File "{0}" -Run' -f $PSCommandPath)
# Starting at the next local 09:00 Manila equivalent keeps polling aligned to the configured send time.
$manila = [TimeZoneInfo]::FindSystemTimeZoneById('Asia/Manila')
$now = [TimeZoneInfo]::ConvertTimeFromUtc([DateTime]::UtcNow, $manila)
$start = $now.Date.AddHours(9)
if ($start -lt $now) { $start = $now.Date.AddMinutes(([Math]::Floor($now.TimeOfDay.TotalMinutes / 5) + 1) * 5) }
$localStart = [TimeZoneInfo]::ConvertTimeFromUtc([TimeZoneInfo]::ConvertTimeToUtc($start, $manila), [TimeZoneInfo]::Local)
$trigger = New-ScheduledTaskTrigger -Once -At $localStart -RepetitionInterval (New-TimeSpan -Minutes 5)
$settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -MultipleInstances IgnoreNew -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit (New-TimeSpan -Minutes 5)
$principal = New-ScheduledTaskPrincipal -UserId ([Security.Principal.WindowsIdentity]::GetCurrent().Name) -LogonType Interactive
Register-ScheduledTask -TaskName 'System Monitoring Daily Teams Report' -Action $action -Trigger $trigger -Settings $settings -Principal $principal -Force | Out-Null
Write-Host 'Scheduled for 9:00 AM Manila time every day while signed in.'
Write-Host 'Place the Excel export in the exports folder as METS-YYYY-MM-DD.xlsx.'
Write-Host 'To send one sample, run: pwsh -File setup.ps1 -TestSend'
