import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import { mkdtemp,rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createDemoStore } from './store.js';
import { createDemoMonitoringRouter } from './router.js';

test('recurrences persist with related tickets, host identity, explicit release links and optional reopening',async t=>{
  const dir=await mkdtemp(join(tmpdir(),'sysmon-bugs-')),file=join(dir,'db.json'),store=await createDemoStore(file);
  // Fixtures use fixed past dates so a same-second creation cannot invalidate the report chronology.
  await store.update(state=>{state.tasks.forEach(task=>task.createdAt='2026-01-01T00:00:00Z');state.deployments=[{id:1,taskId:1,occurredAt:'2026-01-02T00:00:00Z',action:'Fix',version:'Demo'}];});
  const app=express();app.use((req,res,next)=>{req.user={userId:'host-tester'};next();});app.use(createDemoMonitoringRouter(store));
  const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));await rm(dir,{recursive:true,force:true});});
  const request=(path,method='GET',body)=>fetch(`http://127.0.0.1:${server.address().port}${path}`,{method,headers:{'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});
  const task={...store.snapshot().tasks[0],status:'Closed',relatedTickets:['HD-ONE','HD-TWO']};
  assert.equal((await request('/tasks/1','PUT',task)).status,200);
  assert.deepEqual((await (await request('/tasks')).json()).find(task=>task.id===1).relatedTickets,['HD-ONE','HD-TWO']);
  const report={occurredAt:'2026-01-03T00:00:00Z',reference:'HD-RECURRENT',notes:'Bug occurred again after the fix; needs investigation',deploymentId:1,reopen:true,actorId:'forged'};
  assert.equal((await request('/tasks/2/occurrences','POST',report)).status,400);
  assert.equal((await request('/tasks/1/occurrences','POST',{...report,occurredAt:'2025-12-31T00:00:00Z'})).status,400);
  assert.equal((await request('/tasks/1/occurrences','POST',{...report,occurredAt:'2026-01-01T12:00:00Z'})).status,400);
  assert.equal((await request('/tasks/1/occurrences','POST',{...report,deploymentId:999})).status,400);
  assert.equal((await request('/tasks/1/occurrences','POST',{...report,occurredAt:new Date(Date.now()+86400000).toISOString()})).status,400);
  assert.equal((await request('/tasks/1/occurrences','POST',report)).status,201);
  const saved=(await createDemoStore(file)).snapshot();
  assert.equal(saved.bugOccurrences.length,1);assert.equal(saved.bugOccurrences[0].actorId,'host-tester');assert.equal(saved.bugOccurrences[0].deploymentId,1);
  assert.equal(saved.tasks[0].status,'OPEN');assert.equal(saved.tasks[0].completedAt,null);assert.deepEqual(saved.tasks[0].relatedTickets,['HD-ONE','HD-TWO']);
  assert.match(saved.history.at(-1).notes,/Recurrence reported/);
  assert.equal((await (await request('/bug-occurrences')).json())[0].reference,'HD-RECURRENT');
  const {relatedTickets,...legacyUpdate}=task;
  assert.equal((await request('/tasks/1','PUT',legacyUpdate)).status,200);
  assert.deepEqual(store.snapshot().tasks[0].relatedTickets,['HD-ONE','HD-TWO']);
  assert.equal((await request('/tasks/1/occurrences','POST',{...report,reopen:false,deploymentId:null})).status,201);
  assert.equal(store.snapshot().tasks[0].status,'COMPLETE');
  const resolutions=await (await request('/task-resolutions')).json();
  assert.equal(resolutions.filter(event=>event.taskId===1).length,2);
  const enhancement={...task,title:'Demo enhancement module',type:'Enhancement',system:'Client Portal',moduleName:'Billing',status:'Open'};
  assert.equal((await request('/tasks','POST',{...enhancement,system:'Unknown'})).status,400);
  assert.equal((await request('/tasks','POST',{...enhancement,moduleName:'x'.repeat(121)})).status,400);
  const created=await request('/tasks','POST',enhancement);
  assert.equal(created.status,201);const newId=(await created.json()).id;
  let savedEnhancement=(await (await request('/tasks')).json()).find(task=>task.id===newId);
  assert.equal(savedEnhancement.system,'Client Portal');assert.equal(savedEnhancement.moduleName,'Billing');assert.match(savedEnhancement.taskNumber,/^ENH-/);
  const {moduleName,...oldClient}=enhancement;
  assert.equal((await request(`/tasks/${newId}`,'PUT',oldClient)).status,200);
  savedEnhancement=(await (await request('/tasks')).json()).find(task=>task.id===newId);
  assert.equal(savedEnhancement.moduleName,'Billing');
  assert.equal((await request(`/tasks/${newId}`,'PUT',{...enhancement,system:'Another unsupported system'})).status,400);
});
